#!/usr/bin/env python3
"""gen_data_row.py - emit a hand-written data row .s from the TRUE retail
bytes, on the pad template (9747e7c1 / ae3489da data_80059EB0 class).

The split landings re-home tail fragments as data rows named by their TRUE
VA (label-vs-VA lesson, cron-20261023-0442). The content must come from the
witnessed baseline - the woven-era .s dumps are corrupt by definition - so
this tool reads the gated baseline and formats the spimdisasm-style words:

    dlabel data_<VA>
        /* <yaml_off> <VA> <bytes> */ .word 0x........   (per word)

Usage: python3 tools/gen_data_row.py <target> <yaml_off> <extent>
       yaml_off is the yaml row offset (VA = yaml_off + 0x8001F800);
       extent in bytes; output on stdout (redirect into the new .data.s).
Gated: baseline_witness(target) - refuses unwitnessed baselines. (This
tool is a baseline-only consumer - it never reads the build tree - so the
stale_symbols half of input_gates does not apply; the build elf may
legitimately be absent while a split is being staged.)
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pair_report import REPO, baseline_witness  # noqa: E402

BASE_VA = 0x8001F800


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    t, off_s, ext_s = sys.argv[1], sys.argv[2], sys.argv[3]
    off = int(off_s, 16) if off_s.lower().startswith("0x") else int(off_s, 16)
    ext = int(ext_s, 16) if ext_s.lower().startswith("0x") else int(ext_s, 16)
    ok, problems = baseline_witness(t)
    if not ok:
        print(f"gen_data_row: {t} REFUSED - {'; '.join(problems)}",
              file=sys.stderr)
        return 1
    assert ext % 4 == 0, f"extent 0x{ext:X} not word-aligned"
    path = os.path.join(REPO, f"baselines/{t}.bin")
    blob = open(path, "rb").read()
    va0 = off + BASE_VA
    name = f"data_{va0:08X}"
    words = struct.unpack_from("<%dI" % (ext // 4), blob, off)
    out = []
    out.append('.include "macro.inc"')
    out.append("")
    out.append(".set noat")
    out.append(".set noreorder")
    out.append("")
    out.append('.section .data, "wa"')
    out.append("")
    out.append("/* Generated by spimdisasm 1.42.4 */")
    out.append("")
    out.append(f"nonmatching {name}")
    out.append("")
    out.append(f"dlabel {name}")
    for i, w in enumerate(words):
        o = off + i * 4
        va = va0 + i * 4
        out.append(f"    /* {o:X} {va:08X} {w:08X} */ .word 0x{w:08X}")
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
