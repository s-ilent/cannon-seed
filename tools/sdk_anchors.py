#!/usr/bin/env python3
"""sdk_anchors.py - emit the byte-verified SDK anchor rows, per target.

Reads the committed member report (config/sdk_members.txt, GENERATED by
tools/sdk_members.py) and the Psy-Q archives, and writes
config/sdk_anchors.txt: one row per report placement whose verdict is
`anchored` or `unique`, with the function's extent measured from the
member's own .text symbol table (the next symbol's offset, or the .text
size for the last symbol).

The scanner (tools/scan_functions.py) loads this file and carves the spans
out of the rows the map labels `data` as pinned-class asm rows at their
exact addresses; the extent is what makes the carve END where the member
ends. Verdicts are the report's own definitions; `ambiguous` placements
are NOT evidence and are skipped here.

Row grammar (one function per row, sorted by address):
    0x<vram> 0x<size> <symname> <member> <lib> <verdict>

Regenerate:  python3 tools/sdk_anchors.py --libs ~/psyq/3.3/PSX/LIB
(the report is the evidence base - regenerate IT first when the maps move)
"""

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
REPORT = REPO / "config" / "sdk_members.txt"
OUT = REPO / "config" / "sdk_anchors.txt"

ROW = re.compile(
    r"^//\s+(0x[0-9a-fA-F]+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)(\s|$)")


def load_report():
    """target -> [(vram, lib, member, verdict, symname)] in report order."""
    targets = {}
    cur = None
    for ln in REPORT.read_text(errors="replace").splitlines():
        mt = re.match(r"^// target:\s*(\S+)", ln)
        if mt:
            cur = mt.group(1)
            targets.setdefault(cur, [])
            continue
        m = ROW.match(ln)
        if m and cur:
            targets[cur].append((int(m.group(1), 16), m.group(2),
                                 m.group(3), m.group(4), m.group(5)))
    return targets


def load_extents(libdir: Path):
    """(lib, member, symname) -> extent, from the archives' .text symbols."""
    sys.path.insert(0, str(REPO / "tools"))
    import sdk_members as sm  # noqa: E402

    ext = {}
    clashes = 0
    for libpath in sorted(libdir.glob("LIB*.LIB")):
        try:
            members = sm.parse_archive(libpath)
        except Exception as e:  # noqa: BLE001 - report and move on
            print(f"sdk_anchors: WARNING: {libpath.name}: {e}", file=sys.stderr)
            continue
        for m in members:
            text = m.text()
            if not text:
                continue
            syms = m.text_syms()
            offs = sorted({o for o, _ in syms})
            for soff, sname in syms:
                nxt = next((x for x in offs if x > soff), len(text))
                extent = nxt - soff
                key = (m.lib, m.name, sname)
                if key in ext:
                    if ext[key] != extent:
                        clashes += 1
                    continue  # first definition wins
                ext[key] = extent
    if clashes:
        print(f"sdk_anchors: WARNING: {clashes} extent clash(es) across "
              f"same-named members; first definition kept", file=sys.stderr)
    return ext


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--libs", type=Path, required=True,
                    help="directory holding the Psy-Q LIB*.LIB archives")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv[1:])
    if not REPORT.is_file():
        raise SystemExit(f"missing {REPORT} - run tools/sdk_members.py first")
    if not args.libs.is_dir():
        raise SystemExit(f"{args.libs} is not a directory")

    report = load_report()
    ext = load_extents(args.libs)
    print(f"sdk_anchors: {len(ext)} symbol extents from {args.libs}")

    lines = [
        "// SDK anchor rows - GENERATED by tools/sdk_anchors.py. Do not edit.",
        "//",
        "// Evidence base: config/sdk_members.txt (tools/sdk_members.py) + the",
        "// Psy-Q archives' own .text symbol tables. One row per report",
        "// placement whose verdict is `anchored` or `unique` - NOT `ambiguous`",
        "// (near-identical library stubs; not evidence) - with the function's",
        "// extent from its member: next .text symbol's offset, or .text size",
        "// for the last symbol.",
        "//",
        "// The scanner (tools/scan_functions.py) carves these spans out of the",
        "// rows the map labels `data` as pinned-class asm rows at their exact",
        "// addresses. The extent makes the carve END where the member ends.",
        "// Names are evidence, not configuration: adoption goes through",
        "// config/symbols.curated.txt (read its guard block first).",
        "//",
        "// Regenerate:  python3 tools/sdk_anchors.py --libs <psyq lib dir>",
        "//",
        "//   0x<vram> 0x<size> <symname> <member> <lib> <verdict>",
        "",
    ]
    stats = {}
    for t in sorted(report):
        rows = []
        prev_end = 0
        skipped = {"verdict": 0, "extent": 0, "align": 0, "overlap": 0}
        for vram, lib, member, mark, sname in sorted(report[t]):
            if mark not in ("anchored", "unique"):
                skipped["verdict"] += 1
                continue
            size = ext.get((lib, member, sname))
            if size is None:
                skipped["extent"] += 1
                continue
            if size <= 0 or size % 4:
                skipped["align"] += 1
                continue
            if vram < prev_end:
                skipped["overlap"] += 1
                continue
            rows.append(f"0x{vram:08X} 0x{size:X} {sname} {member} {lib} {mark}")
            prev_end = vram + size
        if not rows:
            continue
        lines.append(f"// target: {t}  ({len(rows)} anchors)")
        lines.extend(rows)
        lines.append("")
        stats[t] = (len(rows), skipped)
        s = skipped
        print(f"  {t:<12} {len(rows):<4} anchors  (skipped: {s['verdict']} verdict, "
              f"{s['extent']} no-extent, {s['align']} align, {s['overlap']} overlap)")

    args.out.write_text("\n".join(lines) + "\n")
    print(f"sdk_anchors: wrote {args.out.relative_to(REPO)} "
          f"({sum(n for n, _ in stats.values())} anchors, "
          f"{len(stats)} targets)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
