#!/usr/bin/env python3
"""sdk_curated.py - adopt the SDK member names the anchor carve made reachable.

The v6 --sdk-anchors rule re-typed ~800 data rows as pinned member rows, so
most member symbols now sit at the start of an `asm` subsegment - the report
marks them `adoptable`. Hand-writing that many curated lines is neither
feasible nor auditable; this tool generates them from the same evidence base,
under the same rules every hand adoption followed.

Reads the committed member report (config/sdk_members.txt, GENERATED by
tools/sdk_members.py) and appends a generated adoption block to
config/symbols.curated.txt: one curated line per report symbol that

  (a) has verdict `anchored` or `unique` - `ambiguous` placements are NOT
      evidence (near-identical library stubs),
  (b) is marked `adoptable` (its address is the start of an asm/c
      subsegment in that target's splat yaml, i.e. the scanner can apply
      it), and
  (c) survives the collision rules below.

Collision rules, applied per target:

  * an address that already holds a curated entry keeps it (hand-written
    facts win over generated ones);
  * a name already curated for the target at another address (the SDK
    veneers, earlier hand adoptions) stays with its existing entry;
  * the same name reachable at several addresses is real - LIBC and LIBC2
    ship the same sources, so both copies can be in the image - but one
    label name can only be applied once: the LOWEST address takes the name,
    the other copies keep func_XXXXXXXX. Deterministic, and nothing false
    is asserted about either copy;
  * two different names claiming one address (never observed; guarded
    anyway): anchored beats unique, then signature-DB agreement, then the
    lowest address - a tie skips all of them loudly.

The generated block sits under a marker line at the end of the file; re-runs
truncate at the marker first, so the hand-written head of the file is never
touched. Names remain symbols-file-only (see the guard block at the top of
config/symbols.curated.txt).

Regenerate:
    python3 tools/sdk_members.py --libs ~/psyq/3.3/PSX/LIB --sigs <sigdir>/330
    python3 tools/sdk_curated.py --libs ~/psyq/3.3/PSX/LIB
(the report is the evidence base - regenerate IT first when the maps move)
"""

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
REPORT = REPO / "config" / "sdk_members.txt"
CURATED = REPO / "config" / "symbols.curated.txt"

MARKER = ("// ==== generated sdk-member adoptions below -- "
          "tools/sdk_curated.py; do not hand-edit below this line ====")

ROW = re.compile(
    r"^//\s+(0x[0-9a-fA-F]+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s*(adoptable)?"
    r"\s*(?:\(sig-db\s+(\w+)\))?")
NAME_OK = re.compile(r"^[A-Za-z_]\w*$")


def load_report_adoptable():
    """target -> [(addr, lib, member, mark, sname, sig)] - adoptable rows
    with an evidence-bearing verdict, in report order."""
    targets = defaultdict(list)
    cur = None
    for ln in REPORT.read_text(errors="replace").splitlines():
        mt = re.match(r"^// target:\s*(\S+)", ln)
        if mt:
            cur = mt.group(1)
            continue
        m = ROW.match(ln)
        if m and cur:
            addr, lib, member, mark, sname, adopt, sig = m.groups()
            if adopt and mark in ("anchored", "unique"):
                targets[cur].append((int(addr, 16), lib, member, mark,
                                     sname, sig))
    return targets


def load_hand_curated():
    """(by_target_addr, by_target_name) from the head of symbols.curated.txt
    (everything above the generated marker, if any)."""
    text = CURATED.read_text(errors="replace")
    cut = text.find(MARKER)
    if cut >= 0:
        text = text[:cut]
    by_addr = defaultdict(dict)
    by_name = defaultdict(dict)
    scope = None
    for ln in text.splitlines():
        mt = re.match(r"\s*//\s*target:\s*(\w+)", ln)
        if mt:
            scope = mt.group(1)
            continue
        m = re.match(r"\s*([A-Za-z_]\w*)\s*=\s*(0x[0-9A-Fa-f]+)", ln)
        if m and scope:
            name, addr = m.group(1), int(m.group(2), 16)
            by_addr[scope][addr] = name
            by_name[scope][name] = addr
    return by_addr, by_name


def load_extents(libdir: Path):
    """(lib, member, symname) -> (soff, extent), first definition wins -
    same measurement as tools/sdk_anchors.py, keeping the symbol offset
    for the evidence comments."""
    sys.path.insert(0, str(REPO / "tools"))
    import sdk_members as sm  # noqa: E402

    ext = {}
    clashes = 0
    for libpath in sorted(libdir.glob("LIB*.LIB")):
        try:
            members = sm.parse_archive(libpath)
        except Exception as e:  # noqa: BLE001 - report and move on
            print(f"sdk_curated: WARNING: {libpath.name}: {e}", file=sys.stderr)
            continue
        for m in members:
            text = m.text()
            if not text:
                continue
            syms = m.text_syms()
            offs = sorted({o for o, _ in syms})
            for soff, sname in syms:
                nxt = next((x for x in offs if x > soff), len(text))
                key = (m.lib, m.name, sname)
                if key in ext:
                    if ext[key] != (soff, nxt - soff):
                        clashes += 1
                    continue  # first definition wins
                ext[key] = (soff, nxt - soff)
    if clashes:
        print(f"sdk_curated: WARNING: {clashes} extent clash(es) across "
              f"same-named members; first definition kept", file=sys.stderr)
    return ext


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--libs", type=Path, required=True,
                    help="directory holding the Psy-Q LIB*.LIB archives")
    args = ap.parse_args(argv[1:])
    if not REPORT.is_file():
        raise SystemExit(f"missing {REPORT} - run tools/sdk_members.py first")
    if not args.libs.is_dir():
        raise SystemExit(f"{args.libs} is not a directory")
    if not CURATED.is_file():
        raise SystemExit(f"missing {CURATED}")

    report = load_report_adoptable()
    hand_addr, hand_name = load_hand_curated()
    ext = load_extents(args.libs)

    adopted = 0
    blocks = [MARKER, "//",
             "// Evidence base: config/sdk_members.txt (tools/sdk_members.py)",
             "// at the Psy-Q release pinned in docs/MATCHING.md 3b, extents",
             "// from the archives' own .text symbol tables. Verdicts and the",
             "// collision rules are documented in tools/sdk_curated.py.",
             "// Names are applied by tools/scan_functions.py - symbols file",
             "// only, never subsegment names.", ""]
    for t in sorted(report):
        cands = report[t]
        h_addr, h_name = hand_addr.get(t, {}), hand_name.get(t, {})

        skipped = defaultdict(int)
        # pass 1: names already curated for this target keep their entry
        pool = []
        for addr, lib, member, mark, sname, sig in cands:
            if not NAME_OK.match(sname):
                skipped["bad-name"] += 1
                continue
            if addr in h_addr:
                skipped["addr-curated"] += 1
                continue
            if sname in h_name:
                skipped["name-curated"] += 1
                print(f"  {t}: {sname} @0x{addr:08X} skipped - name already "
                      f"curated at 0x{h_name[sname]:08X}", file=sys.stderr)
                continue
            pool.append((addr, lib, member, mark, sname, sig))

        # pass 2: same name at several addresses - lowest address takes it
        by_name = defaultdict(list)
        for row in pool:
            by_name[row[4]].append(row)
        pool2 = []
        for sname, rows in by_name.items():
            if len(rows) > 1:
                rows.sort(key=lambda r: r[0])
                for r in rows[1:]:
                    skipped["name-dup"] += 1
                    print(f"  {t}: {sname} @0x{r[0]:08X} skipped - same name "
                          f"adopted at 0x{rows[0][0]:08X} (both copies real; "
                          f"one label each)", file=sys.stderr)
                pool2.append(rows[0])
            else:
                pool2.append(rows[0])

        # pass 3: two names at one address - evidence order, tie skips all
        by_addr = defaultdict(list)
        for row in pool2:
            by_addr[row[0]].append(row)
        chosen = []
        for addr, rows in by_addr.items():
            if len(rows) > 1:
                ranked = sorted(rows, key=lambda r: (
                    0 if r[3] == "anchored" else 1,
                    0 if r[5] == "agree" else 1, r[0], r[4]))
                best, rest = ranked[0], ranked[1:]
                if any((r[3], r[5]) == (best[3], best[5]) for r in rest):
                    for r in rows:
                        skipped["addr-dup"] += 1
                        print(f"  {t}: {r[4]} @0x{addr:08X} skipped - "
                              f"indistinguishable rival claim", file=sys.stderr)
                    continue
                for r in rest:
                    skipped["addr-dup"] += 1
                    print(f"  {t}: {r[4]} @0x{addr:08X} skipped - weaker "
                          f"claim than {best[4]}", file=sys.stderr)
                chosen.append(best)
            else:
                chosen.append(rows[0])

        if not chosen:
            continue
        lines = [f"// target: {t}  ({len(chosen)} sdk-member adoptions)"]
        for addr, lib, member, mark, sname, sig in sorted(chosen):
            note = f"{lib} {member} member"
            e = ext.get((lib, member, sname))
            if e:
                note += f" .text+0x{e[0]:x} (extent 0x{e[1]:x})"
            note += f"; sdk_members.py {mark} placement"
            if sig == "agree":
                note += " + sig-db agrees"
            elif sig:
                note += f" (sig-db {sig})"
            lines.append(f"{sname} = 0x{addr:08X}; // {note}")
        lines.append("")
        blocks.extend(lines)
        adopted += len(chosen)
        s = dict(skipped)
        print(f"  {t:<12} {len(chosen):<4} adopted  (skipped: "
              f"{s.get('bad-name', 0)} bad-name, {s.get('addr-curated', 0)} "
              f"addr-curated, {s.get('name-curated', 0)} name-curated, "
              f"{s.get('name-dup', 0)} name-dup, {s.get('addr-dup', 0)} "
              f"addr-dup)")

    if adopted:
        head = CURATED.read_text(errors="replace")
        cut = head.find(MARKER)
        if cut >= 0:
            head = head[:cut].rstrip("\n") + "\n"
        CURATED.write_text(head + "\n".join(blocks).rstrip("\n") + "\n")
        print(f"sdk_curated: {adopted} adoptions -> "
              f"{CURATED.relative_to(REPO)}")
    else:
        print("sdk_curated: nothing to adopt")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
