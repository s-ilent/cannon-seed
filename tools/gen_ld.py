#!/usr/bin/env python3
"""gen_ld.py - generate the round-trip linker script for one target.

splat 0.50's own script groups input sections by type (all .text, then all
.data, ...) which reorders an interleaved PS-X image. This generator reads
the committed splat yaml (one code segment, subsegments in payload order)
and emits one output section per subsegment at its explicit vram and rom
(LMA) address, preserving the retail byte order exactly.

Every staged object contributes exactly ONE input section (.r_<rom>,
rewritten by tools/build.sh), so each output section is a single
contiguous chunk: no SUBALIGN games, no hidden padding.

Usage: python3 tools/gen_ld.py [TARGET]   (default slps_00270)
Output: build/<TARGET>.gen.ld
"""

import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
BASE = 0x80020000
HDR = 0x800


def obj_rel_path(name: str, typ: str, asm_path: str) -> str:
    """Object path the ld script references, relative to repo root.

    tools/build.sh stages every source under build/<path minus the leading
    'asm/'>, so the object lives at build/<asm_path minus 'asm/'>/<file>.o.
    asm_path comes from the target's own splat yaml (per-target asm trees,
    e.g. asm/nonmatchings for slps_00270 or asm/sces_00269/nonmatchings).

    Type `c` subsegments are matched C functions: tools/build.sh compiles
    src/<name>.c through tools/cc.sh (Psy-Q-era cc1 under qemu) and lays
    the object at build/src/<name>.o with .text renamed to .r_<rom>.
    """
    if typ == "c":
        return f"build/src/{name}.o"
    if typ == "data":
        src = f"{asm_path}/data/{name}.data.s"
    else:
        src = f"{asm_path}/{name}.s"
    prefix = "asm/"
    assert src.startswith(prefix), f"asm_path must live under asm/: {src}"
    # staged tree: build/asm/<path minus leading 'asm/'>, obj adds .o
    return f"build/asm/{src[len(prefix):]}.o"


def main(argv):
    target = argv[1] if len(argv) > 1 else "slps_00270"
    cfg = yaml.safe_load((REPO / "config" / f"splat.{target}.yaml").read_text())
    asm_path = cfg["options"]["asm_path"].rstrip("/")

    segs = cfg["segments"]
    code = [s for s in segs if isinstance(s, dict) and s.get("type") == "code"]
    if len(code) != 1:
        raise SystemExit(f"expected exactly one code segment, found {len(code)}")
    code = code[0]
    base_vram = code["vram"]

    subs = []
    for entry in code.get("subsegments", []):
        if not isinstance(entry, list):
            continue
        rom, typ, name = entry[0], entry[1], entry[2]
        subs.append((rom, typ, name))

    lines = [
        f"/* GENERATED by tools/gen_ld.py for {target} - do not edit.",
        " * One output section per subsegment, explicit vram + rom (AT),",
        " * payload order. The PS-X EXE header is added by tools/mkpsxexe.py.",
        " * A single PHDR keeps 500+ sections inside one program header. */",
        "PHDRS { payload PT_LOAD; }",
        "SECTIONS",
        "{",
        "    HIDDEN(__romPos = 0);",
    ]
    for rom, typ, name in subs:
        vram = base_vram + (rom - HDR)
        sec = f".r_{rom:08X}"
        lines.append(
            f"    .o_{rom:08X} 0x{vram:08X} : AT(0x{rom:X}) "
            f"{{ {obj_rel_path(name, typ, asm_path)}({sec}) }} :payload"
        )
    lines.append("")
    lines.append("    /DISCARD/ : { *(.reginfo) *(.MIPS.abiflags) *(.gnu.attributes) *(.comment) *(.pdr) }")
    lines.append("}")
    out = REPO / "build" / f"{target}.gen.ld"
    out.write_text("\n".join(lines) + "\n")
    print(f"gen_ld: {len(subs)} output sections -> {out.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
