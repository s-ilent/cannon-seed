#!/usr/bin/env bash
# =============================================================================
# tools/permuter/run.sh — refresh + run decomp-permuter on a prepared dir.
#
#     tools/permuter/run.sh <project-dir> [extra permuter args...]
#
# Regenerates the machine-specific pieces of a permuter project directory
# (settings.toml, which must hold absolute paths) and then invokes the
# permuter. Keeps the committed template portable: the .c/.o/compile.sh are
# portable, only settings.toml is not.
#
# Env:
#   PERMUTER      checkout of simonlindholm/decomp-permuter
#                 (default: ../decomp-permuter next to this repo)
#   TOOLROOT      tool root; see tools/permuter/compile.sh
#   PYTHON, PY    interpreters for the permuter and the compile script
# =============================================================================
set -euo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
PROJ="${1:?usage: run.sh <project-dir> [permuter args...]}"; shift
PERMUTER="${PERMUTER:-$(dirname "$REPO")/decomp-permuter}"
TOOLROOT="${TOOLROOT:-/home/z/my-project/tools-local}"
MASPSX="${MASPSX:-/home/z/my-project/tools-src/maspsx/maspsx.py}"
QEMU="${QEMU:-$TOOLROOT/qemu-root/usr/bin/qemu-i386-static}"
PYTHON="${PYTHON:-python3}"
PY="${PY:-$PYTHON}"

BIN="$TOOLROOT/mipsel-root/usr/bin"
OBJDUMP="$BIN/mipsel-linux-gnu-objdump"
export LD_LIBRARY_PATH="$TOOLROOT/mipsel-root/usr/lib/x86_64-linux-gnu${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"

[ -x "$OBJDUMP" ] || { echo "run.sh: no objdump at $OBJDUMP" >&2; exit 2; }
[ -f "$PERMUTER/permuter.py" ] || {
    echo "run.sh: no permuter at $PERMUTER (clone simonlindholm/decomp-permuter, or set PERMUTER)" >&2
    exit 2
}
[ -f "$PROJ/target.o" ] || { echo "run.sh: $PROJ/target.o missing" >&2; exit 2; }
[ -f "$PROJ/base.c" ] || { echo "run.sh: $PROJ/base.c missing" >&2; exit 2; }

# Install the canonical compile script into the project: the permuter
# requires compile.sh to live in the directory it is given, and copying it
# here keeps one source of truth for the pipeline.
cp -f "$REPO/tools/permuter/compile.sh" "$PROJ/compile.sh"
chmod +x "$PROJ/compile.sh"

# The permuter looks for mips-linux-gnu-objdump / mips64-*-objdump on PATH,
# but the pinned binutils is mipsel- prefixed. A PATH-compatible symlink is
# cleaner than a settings.toml override, because an override replaces the
# arch's entire argument list (-drz -m mips:4300) and silently drops it.
LINK="$BIN/mips-linux-gnu-objdump"
[ -e "$LINK" ] || ln -s mipsel-linux-gnu-objdump "$LINK"

export PATH="$BIN:$PATH"
# The permuter runs compile.sh as a subprocess from inside the project dir,
# which is usually outside the repo — so hand it the repo root explicitly
# rather than letting it infer one from its own location.
export REPO
export TOOLROOT MASPSX QEMU PYTHON

# settings.toml carries absolute paths, so regenerate it per machine.
cat > "$PROJ/settings.toml" <<EOF
# Generated by tools/permuter/run.sh — machine-specific, do not commit.
# Psy-Q GCC 2.6.3 (MIPS1); the permuter has no mips-gcc profile, so the
# nearest weight family is "gcc".
compiler_type = "gcc"
EOF

exec "$PY" "$PERMUTER/permuter.py" "$PROJ" "$@"
