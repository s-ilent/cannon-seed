#!/usr/bin/env python3
"""gen_watchlist.py - emit a PCSX-Redux coverage driver for one target.

Reads the committed splat yaml (layout ground truth) and the retail
baseline, then writes build/cov.<target>.lua: a Lua driver that lists

  entries  - every code subsegment start (candidate function entries), VRAM
  indirect - every register-form jr/jalr dispatch site inside code, with the
             source register, so the tracer can log the jump target

The driver sets a COV table and dofiles tools/pcsx_coverage.lua, which
registers the breakpoints and logs hits as COV| lines for
tools/coverage_vs_fragments.py.

Usage: python3 tools/gen_watchlist.py [TARGET]   (default slps_00270)
"""
import re
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
VLOAD = 0x80020000
HDR = 0x800


def parse_subsegs(target):
    """Return (payload_offset, type, name) for each yaml subsegment."""
    subs = []
    for ln in (REPO / "config" / f"splat.{target}.yaml").read_text().splitlines():
        m = re.match(r"\s*-\s*\[(0x[0-9A-Fa-f]+),\s*(asm|c|data),\s*(\w+)\]", ln)
        if m:
            subs.append((int(m.group(1), 16) - HDR, m.group(2), m.group(3)))
    return subs


def indirect_sites(target):
    """(vram, rs) for every register-form jr/jalr inside the target's code."""
    code_ranges = []
    for ln in (REPO / "config" / f"splat.{target}.yaml").read_text().splitlines():
        m = re.match(r"\s*-\s*\[(0x[0-9A-Fa-f]+),\s*(asm|c|data),\s*(\w+)\]\s*#\s*(0x[0-9A-Fa-f]+)",
                     ln)
        if m and m.group(2) in ("asm", "c"):
            s = int(m.group(1), 16) - HDR
            code_ranges.append((s, s + int(m.group(4), 16)))

    def in_code(off):
        return any(s <= off < e for s, e in code_ranges)

    payload = (REPO / "baselines" / f"{target}.bin").read_bytes()[HDR:]
    n = len(payload) // 4
    words = struct.unpack(f"<{n}I", payload[: n * 4])
    out = []
    for i, w in enumerate(words):
        if (w >> 26) != 0:
            continue
        if (w & 0x3F) not in (8, 9):        # jr / jalr
            continue
        rs = (w >> 21) & 31
        if rs in (0, 31):                   # jr $zero (noreturn); jr $ra (return)
            continue
        if in_code(i * 4):                  # a jr-looking word in data is not a jump
            out.append((VLOAD + i * 4, rs))
    return out


def main(argv):
    args = [a for a in argv[1:] if not a.startswith("--")]
    target = args[0] if args else "slps_00270"
    stop = []
    if "--stop" in argv:
        stop = [int(x, 16) for x in argv[argv.index("--stop") + 1].split(",")]
    mark = []
    if "--mark" in argv:
        mark = [int(x, 16) for x in argv[argv.index("--mark") + 1].split(",")]
    merge = []
    if "--merge" in argv:
        merge = argv[argv.index("--merge") + 1].split(",")

    if merge:
        stages = merge
        target = "+".join(merge)
        for t in merge:
            head = (REPO / "baselines" / f"{t}.bin").read_bytes()[:0x20]
            mark.append(struct.unpack_from("<I", head, 0x10)[0])
    else:
        stages = [target]

    # Expected instruction word per stage at each address. Every stage loads at
    # the same base, so a hit only counts when the live word matches that
    # stage's image; code from another stage occupying the same RAM is never
    # miscounted. This is per-stage attribution without phase splitting.
    images = {st: (REPO / "baselines" / f"{st}.bin").read_bytes()[HDR:] for st in stages}
    addrs = sorted({VLOAD + s for st in stages
                    for s, ty, n in parse_subsegs(st) if ty in ("asm", "c")})
    entries = []
    for a in addrs:
        off = a - VLOAD
        words = [struct.unpack_from("<I", images[st], off)[0]
                 if off + 4 <= len(images[st]) else 0 for st in stages]
        entries.append((a, words))

    indirect = [] if merge else indirect_sites(target)

    if "--entries-only" in argv:
        indirect = []

    out_dir = REPO / "build"
    out_dir.mkdir(exist_ok=True)
    cov_out = out_dir / f"coverage.{target}.txt"
    drv = out_dir / f"cov.{target}.lua"
    tracer = (Path(__file__).resolve().parent / "pcsx_coverage.lua")

    with drv.open("w") as fh:
        fh.write("-- generated by tools/gen_watchlist.py - do not edit\n")
        fh.write("COV = {\n")
        fh.write(f'  target = "{target}",\n')
        fh.write(f'  out = "{cov_out}",\n')
        fh.write("  stages = {\n")
        for st in stages:
            fh.write(f'    "{st}",\n')
        fh.write("  },\n")
        fh.write("  entries = {\n")
        for a, words in entries:
            ws = ", ".join(f"0x{w:08X}" for w in words)
            fh.write(f"    {{ a = 0x{a:08X}, w = {{ {ws} }} }},\n")
        fh.write("  },\n")
        fh.write("  indirect = {\n")
        for a, rs in indirect:
            fh.write(f"    {{ a = 0x{a:08X}, rs = {rs} }},\n")
        fh.write("  },\n")
        if stop:
            fh.write("  stopAt = {\n")
            for a in stop:
                fh.write(f"    0x{a:08X},\n")
            fh.write("  },\n")
        if mark:
            fh.write("  markAt = {\n")
            for a in mark:
                fh.write(f"    0x{a:08X},\n")
            fh.write("  },\n")
        fh.write("}\n")
        fh.write(f'dofile("{tracer}")\n')

    print(f"{target}: {len(entries)} entry breakpoints, "
          f"{len(indirect)} indirect sites -> {drv.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
