#!/usr/bin/env python3
"""data_stub_recarve_mmj.py - mainmenu_jp data_80066CF4 re-carve stub surgery.

The yaml re-carve splits the 0x520 graveyard data row into:
  0x3E1B4  data data_80066CF4  0x8    (row head keeps the graveyard name)
  0x3E1BC  c    func_80048EC0  0x160  (the landed GTE transform host copy)
  0x3E31C  data data_8005DB1C  0x2d8  (new VA-derived name)
  0x3E5F4  c    func_800492F8  0x110  (the landed GTE rotation-matrix composer)
absorbing the [0x3E6D4 c func_8005DED4] tail row.

Data rows link through COMMITTED spimdisasm stubs (asm/<t>/nonmatchings/data/
<yaml-name>.data.s), so this script:
  1. shrinks data_80066CF4.data.s to its first 2 words (0x8) + enddlabel;
  2. emits data_8005DB1C.data.s carrying the old stub's word lines for
     0x3E31C..0x3E5F4 verbatim, preserving the interior dlabel scaffolding
     for the blocks fully inside the new row (func_8005DBA0, func_8005DC34,
     func_8005DCD8, func_8005DD80 - all referenced, names must survive);
     the two straddling labels are dropped: func_8005DAFC (head 0x3E2FC now
     inside the func_80048EC0 c span; ZERO live refs repo-wide) and
     func_8005DE24 (0x3E624 now inside the func_800492F8 c span; only a
     provenance-comment mention in src/func_8005DED4.c).
verify is the arbiter; revert = git checkout the stub + yaml.
"""
from pathlib import Path

STUB_DIR = Path("asm/mainmenu_jp/nonmatchings/data")
OLD = STUB_DIR / "data_80066CF4.data.s"
NEW = STUB_DIR / "data_8005DB1C.data.s"

lines = OLD.read_text().splitlines()

# --- sanity: anchor lines (1-indexed as mapped from the committed stub) ------
def expect(idx1, needle):
    ln = lines[idx1 - 1]
    assert needle in ln, f"line {idx1} mismatch: {ln!r} lacks {needle!r}"

expect(10, "3E1B4")
expect(11, "3E1B8")
expect(12, "3E1BC")
expect(120, "3E31C")
expect(152, "3E39C")
expect(153, "enddlabel func_8005DAFC")
expect(158, "3E3A0")
expect(194, "3E430")
expect(200, "3E434")
expect(240, "3E4D4")
expect(246, "3E4D8")
expect(287, "3E57C")
expect(293, "3E580")
expect(321, "3E5F0")
expect(322, "3E5F4")

# --- 1. shrink the old stub to 0x8 -------------------------------------------
shrunk = lines[:11] + ["enddlabel func_8005D9B4", ""]
OLD.write_text("\n".join(shrunk))
print(f"shrunk {OLD} -> 2 words (0x8)")

# --- 2. emit the new stub ------------------------------------------------------
def block(name, lo, hi):
    out = ["", f"nonmatching {name}", "", f"dlabel {name}"]
    out += lines[lo - 1 : hi]
    out.append(f"enddlabel {name}")
    return out

new = [
    '.include "macro.inc"',
    "",
    '.section .data, "wa"',
    "",
    "/* Generated by spimdisasm 1.42.4 */",
    "",
    "nonmatching func_8005DB1C",
    "",
    "dlabel func_8005DB1C",
]
new += lines[119:152]  # 0x3E31C..0x3E39C (tail of the old 8005DAFC block)
new += block("func_8005DBA0", 158, 194)   # 0x3E3A0..0x3E434
new += block("func_8005DC34", 200, 240)   # 0x3E434..0x3E4D8
new += block("func_8005DCD8", 246, 287)   # 0x3E4D8..0x3E580
new += block("func_8005DD80", 293, 321)   # 0x3E580..0x3E5F4
new.append("")
NEW.write_text("\n".join(new))

words = sum(1 for ln in new if ".word" in ln)
assert words == 182, f"new stub word count {words} != 182 (0x2d8)"
print(f"wrote {NEW} ({words} words = 0x{words*4:x}, expected 0x2d8)")
