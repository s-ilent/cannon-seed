#!/usr/bin/env python3
"""wire_split.py - wire the slps block-move unit split IN-TREE for judging.

Rehearsal numbers from STATE.md (cron-202610260919):
  - yaml: [0x7AF8, asm, func_800272F8] # 0x54b8 becomes
      [0x7AF8, asm, func_800272F8]   # 0x3aa8
      [0xB5A0, c,   func_8002ADA0]   # 0x6c4
      [0xBC64, asm, func_8002B464]   # 0x134c
  - asm: unit lines 5374..5971 leave func_800272F8.s; the tail
    (5972..EOF) becomes asm/nonmatchings/func_8002B464.s.
  - src: the candidate .c lands at src/func_8002ADA0.c.
  - generated table: appends the unit's eight data symbols with
    absolute:true to config/symbols.slps_00270.txt (the curated file is
    the durable source; gp_flags.py reads ONLY the generated table, so
    the judge mini-link fails GPREL16 without this session-local append).

Usage: wire_split.py <candidate.c>
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
YAML = os.path.join(REPO, "config/splat.slps_00270.yaml")
GIANT = os.path.join(REPO, "asm/nonmatchings/func_800272F8.s")
TAIL = os.path.join(REPO, "asm/nonmatchings/func_8002B464.s")
SRC_DST = os.path.join(REPO, "src/func_8002ADA0.c")

OLD_LINE = "      - [0x7AF8, asm, func_800272F8]   # 0x54b8\n"
NEW_LINES = (
    "      - [0x7AF8, asm, func_800272F8]   # 0x3aa8\n"
    "      - [0xB5A0, c, func_8002ADA0]   # 0x6c4\n"
    "      - [0xBC64, asm, func_8002B464]   # 0x134c\n"
)

TAIL_HEADER = (
    '.include "macro.inc"\n'
    "\n"
    ".set noat\n"
    ".set noreorder\n"
    "\n"
    '.section .text, "ax"\n'
    "\n"
    "/* Generated by spimdisasm 1.42.4 */\n"
    "\n"
)


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    cand = os.path.abspath(sys.argv[1])

    # 1. yaml split
    y = open(YAML).read()
    if OLD_LINE not in y:
        if "[0xB5A0, c, func_8002ADA0]" in y:
            print("yaml already split")
        else:
            print("yaml anchor line not found", file=sys.stderr)
            return 1
    else:
        open(YAML, "w").write(y.replace(OLD_LINE, NEW_LINES))
        print("yaml split written")

    # 2. asm surgery
    lines = open(GIANT).read().splitlines(keepends=True)
    if len(lines) == 7650:
        head = lines[:5373]          # 1..5373
        tail = lines[5971:]          # 5972..EOF
        open(GIANT, "w").writelines(head)
        with open(TAIL, "w") as f:
            f.write(TAIL_HEADER)
            f.writelines(tail)
        print(f"asm cut: giant keeps {len(head)} lines, tail file {len(tail)} lines")
    elif os.path.exists(TAIL):
        print("asm already cut")
    else:
        print(f"unexpected giant line count {len(lines)}", file=sys.stderr)
        return 1

    # 3. src
    open(SRC_DST, "w").write(open(cand).read())
    print(f"src written from {os.path.basename(cand)}")

    # 4. generated-table append (session-local; curated file is durable)
    GEN = os.path.join(REPO, "config/symbols.slps_00270.txt")
    marker = "// END GENERATED DATA SYMBOLS"
    txt = open(GEN).read()
    if "D_8006974C" not in txt:
        assert marker in txt, "generated table marker missing"
        entries = "".join(
            f"{n} = 0x{a:X}; // type:s32 absolute:true\n" for n, a in [
                ("D_8006974C", 0x8006974C), ("D_801150F8", 0x801150F8),
                ("D_801150F9", 0x801150F9), ("D_801150FA", 0x801150FA),
                ("D_801150FB", 0x801150FB), ("D_80115158", 0x80115158),
                ("D_801151F8", 0x801151F8), ("D_80115278", 0x80115278)])
        open(GEN, "w").write(txt.replace(marker, entries + marker))
        print("generated table: 8 absolute:true entries appended")
    else:
        print("generated table already carries the unit entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
