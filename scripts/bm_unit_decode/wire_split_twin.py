#!/usr/bin/env python3
"""wire_split_twin.py - wire the SCES block-move unit split IN-TREE for judging.

The sces twin of wire_split.py (slps func_8002ADA0). Boundaries measured
cron-20261026-2119 off the committed tree (the staged decode artifact
scripts/bm_unit_decode/func_8002ABC8.c records the extents: sces_00269 unit
VA 0x8002ABC8..0x8002B28C, yaml/file 0xB3C8..0xBA8C, 0x6c4 bytes, carved out
of the giant boot row at its true entry - the jal'd prologue - through its
epilogue; the shared k=6 epilogue thunk func_8002B26C is the twin region's
last 0x20 bytes, exactly like slps's func_8002B444).

Rehearsal numbers (mirror of the slps split; the twin region is 598 lines,
IDENTICAL to slps's 598):
  - yaml: [0x7B40, asm, func_80027340] # 0x528c becomes
      [0x7B40, asm, func_80027340]   # 0x3888
      [0xB3C8, c,   func_8002ABC8]   # 0x6c4
      [0xBA8C, asm, func_8002B28C]   # 0x1340
  - asm: giant asm/sces_00269/nonmatchings/func_80027340.s (7451 lines);
    twin region = lines 5183..5780 (starts "nonmatching func_8002ABC8, 0x40",
    ends "endlabel func_8002B26C") leave the giant; the tail
    (5781..EOF, starts "nonmatching func_8002B28C, 0x8") becomes
    asm/sces_00269/nonmatchings/func_8002B28C.s.
  - src: the candidate .c lands at src/func_8002ABC8.c.
  - generated table: appends the twin's nine data symbols with
    absolute:true to config/symbols.sces_00269.txt (the curated file is
    the durable source; gp_flags.py reads ONLY the generated table, so
    the judge mini-link fails GPREL16 without this session-local append).

Usage: wire_split_twin.py <candidate.c>
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
YAML = os.path.join(REPO, "config/splat.sces_00269.yaml")
GIANT = os.path.join(REPO, "asm/sces_00269/nonmatchings/func_80027340.s")
TAIL = os.path.join(REPO, "asm/sces_00269/nonmatchings/func_8002B28C.s")
SRC_DST = os.path.join(REPO, "src/func_8002ABC8.c")

OLD_LINE = "      - [0x7B40, asm, func_80027340]   # 0x528c\n"
NEW_LINES = (
    "      - [0x7B40, asm, func_80027340]   # 0x3888\n"
    "      - [0xB3C8, c, func_8002ABC8]   # 0x6c4\n"
    "      - [0xBA8C, asm, func_8002B28C]   # 0x1340\n"
)

# 0-based slice bounds into the giant (7451 lines):
#   head = lines[:5182]          (1..5182)
#   twin = lines[5182:5780]      (5183..5780, DISCARDED - the C replaces it)
#   tail = lines[5780:]          (5781..EOF)
HEAD_END = 5182
TAIL_START = 5780
TWIN_FIRST = "nonmatching func_8002ABC8, 0x40"
TWIN_LAST = "endlabel func_8002B26C"
TAIL_FIRST = "nonmatching func_8002B28C, 0x8"

TAIL_HEADER = (
    '.include "macro.inc"\n'
    "\n"
    ".set noat\n"
    ".set noreorder\n"
    "\n"
    '.section .text, "ax"\n'
    "\n"
    "/* Generated by spimdisasm 1.42.4 */\n"
    "\n"
)

DATA_SYMBOLS = [
    ("D_800693F4", 0x800693F4),  # the 0x200 work buffer
    ("D_80114678", 0x80114678),  # 'SC'+code header
    ("D_80114679", 0x80114679),
    ("D_8011467A", 0x8011467A),
    ("D_8011467B", 0x8011467B),  # sector-count byte -> create-open flags
    ("D_801146D8", 0x801146D8),  # the 0x30 name record
    ("D_801146F8", 0x801146F8),  # first block-move dst
    ("D_80114778", 0x80114778),
    ("D_801147F8", 0x801147F8),
]


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    cand = os.path.abspath(sys.argv[1])

    # 1. yaml split
    y = open(YAML).read()
    if OLD_LINE not in y:
        if "[0xB3C8, c, func_8002ABC8]" in y:
            print("yaml already split")
        else:
            print("yaml anchor line not found", file=sys.stderr)
            return 1
    else:
        open(YAML, "w").write(y.replace(OLD_LINE, NEW_LINES))
        print("yaml split written")

    # 2. asm surgery
    lines = open(GIANT).read().splitlines(keepends=True)
    if (len(lines) == 7451
            and lines[HEAD_END].startswith(TWIN_FIRST)
            and lines[TAIL_START - 2].startswith(TWIN_LAST)
            and lines[TAIL_START].startswith(TAIL_FIRST)):
        head = lines[:HEAD_END]
        tail = lines[TAIL_START:]
        open(GIANT, "w").writelines(head)
        with open(TAIL, "w") as f:
            f.write(TAIL_HEADER)
            f.writelines(tail)
        print(f"asm cut: giant keeps {len(head)} lines, "
              f"twin region {TAIL_START - HEAD_END} lines discarded, "
              f"tail file {len(tail)} lines")
    elif os.path.exists(TAIL):
        print("asm already cut")
    else:
        print(f"unexpected giant state: {len(lines)} lines, "
              f"lines[{HEAD_END}]={lines[HEAD_END] if lines else None!r}",
              file=sys.stderr)
        return 1

    # 3. src
    open(SRC_DST, "w").write(open(cand).read())
    print(f"src written from {os.path.basename(cand)}")

    # 4. generated-table append (session-local; curated file is durable)
    GEN = os.path.join(REPO, "config/symbols.sces_00269.txt")
    marker = "// END GENERATED DATA SYMBOLS"
    txt = open(GEN).read()
    if "D_800693F4" not in txt:
        assert marker in txt, "generated table marker missing"
        entries = "".join(
            f"{n} = 0x{a:X}; // type:s32 absolute:true\n" for n, a in DATA_SYMBOLS)
        open(GEN, "w").write(txt.replace(marker, entries + marker))
        print(f"generated table: {len(DATA_SYMBOLS)} absolute:true entries appended")
    else:
        print("generated table already carries the twin entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
