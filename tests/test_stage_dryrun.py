#!/usr/bin/env python3
"""tests/test_stage_dryrun.py - the validator must be able to fail.

A staged-recipe dry-run that always prints ALL CHECKS PASS is worthless:
its value is catching a drifted anchor BEFORE an oracle window spends its
minutes on a wrong cut. These tests calibrate the engine on a synthetic
fixture tree (temp dir, no baselines, no build tree - fully offline):

  * the good fixture passes (the engine's happy path end to end);
  * each tampered variant fails ON THE RIGHT CHECK class:
      - a boundary word mutated       -> boundary check
      - an orphan enddlabel removed   -> labels-balance / orphan check
      - the yaml extent comment lying -> yaml-row-extent check
      - a duplicated c word           -> piece word-count / tiling check
      - a cross-target same-name ref  -> NOT counted (per-target scoping)

The fixture mirrors the staged-recipe shape at micro scale: one covering
data row (head 0x20 / c 0x8 / tail 0x18), the walk dlabel named by its
true VA, one external jal reference, and the yaml with the next row
abutting.
"""
import os
import struct
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "tools"))
import stage_dryrun  # noqa: E402

BASE_VA = stage_dryrun.BASE_VA


def word_line(off, word):
    va = off + BASE_VA
    enc = struct.pack("<I", word).hex().upper()
    return f"    /* {off:X} {va:08X} {enc} */ .word 0x{word:08X}"


HEAD_WORDS = [0x27BDFFE8, 0xAFB00010, 0x0C000000, 0x00000000,
              0x8FA40010, 0x00851021, 0x03E00008, 0x00000000]
C_WORDS = [0x34021000, 0xAC800018]
TAIL_WORDS = [0x27BDFFE8, 0xAFB00010, 0xAC840000, 0x00851021,
              0x03E00008, 0x00000000]

WALK = "func_8001FB00"          # name-VA law: content VA at file_off 0x300
ROW_YAML = 0x300
ROW_EXTENT = 0x40               # head 0x20 + c 0x8 + tail 0x18


def render_row(head_words=None, c_words=None, tail_words=None,
               with_orphan=True):
    head_words = HEAD_WORDS if head_words is None else head_words
    c_words = C_WORDS if c_words is None else c_words
    tail_words = TAIL_WORDS if tail_words is None else tail_words
    out = [
        '.include "macro.inc"',
        "",
        '.section .data, "wa"',
        "",
        "/* Generated by spimdisasm 1.42.4 */",
        "",
        f"nonmatching {WALK}",
        "",
        f"dlabel {WALK}",
    ]
    off = ROW_YAML
    for w in head_words:
        out.append(word_line(off, w))
        off += 4
    out.append(word_line(off, C_WORDS[0] if c_words is None or not c_words else c_words[0]))
    off += 4
    for w in (c_words[1:] if c_words else C_WORDS[1:]):
        out.append(word_line(off, w))
        off += 4
    if with_orphan:
        out.append(f"enddlabel {WALK}")
    out.append("")
    for w in tail_words:
        out.append(word_line(off, w))
        off += 4
    return out, off


def write_fixture(root: Path, head_words=None, c_words=None,
                  tail_words=None, with_orphan=True, row_extent=ROW_EXTENT,
                  extra_target_file=None):
    tgt = root / "asm" / "tgt" / "nonmatchings" / "data"
    tgt.mkdir(parents=True)
    lines, end_off = render_row(head_words, c_words, tail_words, with_orphan)
    (tgt / "data_300.data.s").write_text("\n".join(lines) + "\n")
    # one external jal reference INSIDE the target
    ref = root / "asm" / "tgt" / "nonmatchings" / "func_999.s"
    ref.write_text(f"nonmatching func_999\n\n    jal {WALK}\n")
    if extra_target_file is not None:
        # a same-named label referenced from ANOTHER target (must not count)
        other = root / "asm" / "other" / "nonmatchings"
        other.mkdir(parents=True)
        (other / "func_998.s").write_text(
            f"nonmatching func_998\n\n    jal {WALK}\n    jal {WALK}\n")
    cfg = root / "config"
    cfg.mkdir()
    (cfg / "splat.tgt.yaml").write_text(
        f"      - [0x{ROW_YAML:X}, data, data_300]   # 0x{row_extent:x}\n"
        f"      - [0x{ROW_YAML + row_extent:X}, asm, func_8001FB40]   # 0x10\n")
    return end_off


def make_recipe(tail_last=None):
    return dict(
        target="tgt",
        src="asm/tgt/nonmatchings/data/data_300.data.s",
        yaml="config/splat.tgt.yaml",
        row_label="data_300", row_yaml=ROW_YAML, row_extent=ROW_EXTENT,
        walk_label=WALK, walk_rel=0x20,
        head_extent=0x20, head_last=17, append_enddlabel=WALK,
        pieces=[
            dict(kind="c", label="GsThing", yaml=ROW_YAML + 0x20,
                 extent=0x8, first=18, last=19),
            dict(kind="tail", label="data_328", yaml=ROW_YAML + 0x28,
                 extent=0x18, first=22, last=27,
                 tail_ranges=[(22, tail_last)]),
        ],
        orphan_line=20, orphan_text=f"enddlabel {WALK}",
        boundary={17: 0x00000000, 18: 0x34021000, 19: 0xAC800018,
                  22: 0x27BDFFE8},
        refs={WALK: 1},
    )


class StageDryrunTest(unittest.TestCase):
    def setUp(self):
        self._old_repo = stage_dryrun.REPO
        self._tmp = tempfile.mkdtemp(prefix="stage_dryrun_test_")
        self.root = Path(self._tmp)
        stage_dryrun.REPO = self.root

    def tearDown(self):
        stage_dryrun.REPO = self._old_repo

    def run_recipe(self, recipe):
        import io
        from contextlib import redirect_stdout
        buf = io.StringIO()
        with redirect_stdout(buf):
            rc = stage_dryrun.run_recipe("test", recipe)
        return rc, buf.getvalue()

    def test_good_fixture_passes(self):
        write_fixture(self.root)
        rc, out = self.run_recipe(make_recipe())
        self.assertEqual(rc, 0, out)
        self.assertIn("ALL CHECKS PASS", out)

    def test_mutated_boundary_word_fails(self):
        c_words = [0x34021000, 0xAC800019]  # last c word off by one bit
        write_fixture(self.root, c_words=c_words)
        rc, out = self.run_recipe(make_recipe())
        self.assertEqual(rc, 1)
        self.assertIn("[FAIL] boundary line 19", out)

    def test_missing_orphan_fails(self):
        write_fixture(self.root, with_orphan=False)
        rc, out = self.run_recipe(make_recipe())
        self.assertEqual(rc, 1)
        self.assertIn("[FAIL]", out)

    def test_lying_yaml_extent_fails(self):
        write_fixture(self.root)
        rc, out = self.run_recipe(make_recipe())
        self.assertEqual(rc, 0, out)
        # now claim the row is one word longer than the next row allows
        recipe = make_recipe()
        recipe["row_extent"] = 0x44
        rc, out = self.run_recipe(recipe)
        self.assertEqual(rc, 1)
        self.assertIn("[FAIL] yaml-next-row-abuts", out)

    def test_duplicated_c_word_fails(self):
        # one extra word in the source's c span shifts every later anchor
        lines, _ = render_row()
        extra = word_line(0x320 + 8, 0x00000000)
        lines[19:19] = [extra]
        tgt = self.root / "asm" / "tgt" / "nonmatchings" / "data"
        tgt.mkdir(parents=True)
        (tgt / "data_300.data.s").write_text("\n".join(lines) + "\n")
        ref = self.root / "asm" / "tgt" / "nonmatchings" / "func_999.s"
        ref.write_text(f"nonmatching func_999\n\n    jal {WALK}\n")
        cfg = self.root / "config"
        cfg.mkdir()
        (cfg / "splat.tgt.yaml").write_text(
            f"      - [0x{ROW_YAML:X}, data, data_300]   # 0x{ROW_EXTENT:x}\n"
            f"      - [0x{ROW_YAML + ROW_EXTENT:X}, asm, func_8001FB40]   # 0x10\n")
        rc, out = self.run_recipe(make_recipe())
        self.assertEqual(rc, 1)
        self.assertIn("[FAIL]", out)

    def test_cross_target_refs_not_counted(self):
        write_fixture(self.root, extra_target_file=True)
        rc, out = self.run_recipe(make_recipe())
        self.assertEqual(rc, 0, out)
        self.assertIn("ALL CHECKS PASS", out)

    def test_line_drift_fails(self):
        # upstream inserted a line before the c region: every anchor shifts
        write_fixture(self.root)
        recipe = make_recipe()
        recipe["head_last"] = 18
        rc, out = self.run_recipe(recipe)
        self.assertEqual(rc, 1)
        self.assertIn("[FAIL]", out)


if __name__ == "__main__":
    unittest.main()
